import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const read = path => JSON.parse(readFileSync(new URL(path, root), 'utf8'));
export function generateResources() {
  const strings = read('resources/locales/en.json');
  const accessors = Object.entries(strings).map(([key, value]) => {
    const params = [...new Set([...value.matchAll(/\{(\w+)\}/g)].map(match => match[1]))];
    const args = params.map(p => `${p}: string | number`).join(', ');
    const expression = params.reduce((s, p) => `${s}.replaceAll(${JSON.stringify(`{${p}}`)}, String(${p}))`, JSON.stringify(value));
    return `    ${key}: (${args}) => ${expression},`;
  }).join('\n');
  const output = `// Generated by scripts/generate-resources.mjs. Edit resources/ instead.\nexport const res = {\n  str: {\n${accessors}\n  },\n  vectors: ${JSON.stringify(read('resources/vectors.json'), null, 2)},\n  assets: { protocolExamples: ${JSON.stringify(read('resources/protocol-examples.json'), null, 2)}, providers: ${JSON.stringify(read('resources/providers.json'), null, 2)}, document: ${JSON.stringify(read('resources/document.json'), null, 2)}, scenarios: ${JSON.stringify(read('resources/scenarios.json'), null, 2)} },\n} as const;\n`;
  const dir = new URL('src/generated/', root);
  mkdirSync(dir, { recursive: true });
  const target = new URL('res.generated.ts', dir);
  let old; try { old = readFileSync(target, 'utf8'); } catch {}
  if (old !== output) writeFileSync(target, output);
}
if (process.argv[1] === fileURLToPath(import.meta.url)) generateResources();
